"""Regenerate used_modules.txt: the modules the test suite imports.

Runs the full test suite with ``SCANTAILOR_RECORD_IMPORTS`` set (see
tests/conftest.py), then keeps the modules of scantailor and of the runtime
dependencies (the closure of py-scantailor's requirements, no dependency groups).
The frozen checks import every listed module whose package the build bundles,
and bundle_report.py lists bundled modules missing from it for review.

Usage:
    python tools/pyinstaller/record_used_modules.py [--raw FILE] [pytest args]

``--raw`` filters a list an earlier run already recorded instead of running the
tests again.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile
from importlib import metadata
from pathlib import Path
from typing import Final

REPO_ROOT: Final = Path(__file__).resolve().parents[2]
OUTPUT: Final = Path(__file__).with_name("used_modules.txt")
PROJECT: Final = "py-scantailor"
FIRST_PARTY: Final = "scantailor"
# Runtime packages the tests import for their own tooling; the app never does.
TEST_ONLY: Final = (
    "PySide6.QtTest",  # pytest-qt drives widgets with it
    # pytest's pygments loads its image formatter, which draws text with these.
    "PIL.ImageDraw",
    "PIL.ImageFont",
    "PIL.ImageText",
    "PIL._imagingft",
)
_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*")
HEADER: Final = """\
# Modules of scantailor and its runtime dependencies that the test suite imports.
# Generated by tools/pyinstaller/record_used_modules.py; do not edit by hand.
"""


def normalise(name: str) -> str:
    """Normalise a distribution name as PEP 503 does."""
    return re.sub(r"[-_.]+", "-", name).lower()


def runtime_distributions(project: str = PROJECT) -> set[str]:
    """Collect the installed distributions py-scantailor needs at runtime.

    Requirements behind an extra are skipped; platform markers are not
    evaluated, so a dependency of another platform is kept if installed.

    Args:
        project (str): The distribution to start from.

    Returns:
        set[str]: Normalised names of the project and every runtime dependency.
    """
    found: set[str] = set()
    pending = [project]
    while pending:
        name = normalise(pending.pop())
        if name in found:
            continue
        try:
            requirements = metadata.requires(name) or []
        except metadata.PackageNotFoundError:
            continue
        found.add(name)
        for requirement in requirements:
            _, _, marker = requirement.partition(";")
            match = _NAME.match(requirement.strip())
            if match and "extra" not in marker:
                pending.append(match.group(0))
    return found


def runtime_top_levels() -> set[str]:
    """Return the top-level import names that runtime distributions provide."""
    runtime = runtime_distributions()
    return {
        module
        for module, distributions in metadata.packages_distributions().items()
        if any(normalise(name) in runtime for name in distributions)
    } | {FIRST_PARTY}


def filter_modules(loaded: set[str], top_levels: set[str]) -> list[str]:
    """Keep the runtime modules of a recorded module list.

    Args:
        loaded (set[str]): Every module name the test session loaded.
        top_levels (set[str]): Import names of scantailor and its runtime
            dependencies.

    Returns:
        list[str]: The kept names, sorted.
    """
    return sorted(
        name
        for name in loaded
        if name.partition(".")[0] in top_levels
        and not any(
            name == prefix or name.startswith(f"{prefix}.") for prefix in TEST_ONLY
        )
    )


def record(pytest_args: list[str], raw: Path) -> None:
    """Run the whole test suite, recording its imports to ``raw``.

    Raises:
        SystemExit: The test run failed, so the list would be incomplete.
    """
    environment = {**os.environ, "SCANTAILOR_RECORD_IMPORTS": str(raw)}
    command = [sys.executable, "-m", "pytest", "-m", "", "-q", *pytest_args]
    if subprocess.run(command, cwd=REPO_ROOT, env=environment, check=False).returncode:
        raise SystemExit("the test run failed; used_modules.txt is unchanged")


def main(argv: list[str] | None = None) -> int:
    """Record (or read) the imports and write used_modules.txt.

    Args:
        argv (list[str] | None): Command line without the program name.

    Returns:
        int: 0 on success.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--raw", type=Path, help="an already recorded module list")
    args, pytest_args = parser.parse_known_args(argv)
    with tempfile.TemporaryDirectory(prefix="scantailor-imports-") as scratch:
        raw = args.raw
        if raw is None:
            raw = Path(scratch) / "loaded.txt"
            record(pytest_args, raw)
        loaded = set(raw.read_text(encoding="utf-8").split())
    kept = filter_modules(loaded, runtime_top_levels())
    OUTPUT.write_text(HEADER + "\n".join(kept) + "\n", encoding="utf-8")
    print(f"wrote {len(kept)} of {len(loaded)} recorded modules to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
